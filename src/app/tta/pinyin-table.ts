// their pinyin reading; runs of non-Chinese characters (Latin, punctuation,
// digits) are preserved as-is. Pinyin syllables are separated by spaces.
export function textToPinyin(text: string): string {
  let out = "";
  let buf = "";
  const flush = () => {
    if (buf) {
      out += buf;
      buf = "";
    }
  };
  for (const ch of text) {
    const code = ch.codePointAt(0) ?? 0;
    const isChinese = code >= 0x3400 && code <= 0x9fff;
    if (isChinese) {
      flush();
      out += charToPinyin(ch) + " ";
    } else {
      buf += ch;
    }
  }
  flush();
  // Collapse multiple spaces, trim trailing space.
  return out.replace(/[ 	]+/g, " ").trim();
}
