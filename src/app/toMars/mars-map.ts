// Reverse map for 火星文 -> 普通. Built once at module load.
// When multiple 普通 chars map to the same 火星文 glyph, the first wins
// (insertion order). Reverse lookup is best-effort because the mapping
// is intentionally lossy.
export const MARS_REVERSE_MAP: Record<string, string> = (() => {
  const rev: Record<string, string> = {};
  for (const [k, v] of Object.entries(MARS_MAP)) {
    if (!(v in rev)) rev[v] = k;
  }
  return rev;
})();
