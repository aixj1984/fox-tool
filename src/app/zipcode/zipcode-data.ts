export interface ZipLookup {
  province: string;
  city: string;
  zip: string;
}

export function lookupByZip(zip: string): ZipLookup[] {
  const q = zip.trim();
  if (q === "") return [];
  const out: ZipLookup[] = [];
  for (const p of POSTAL_DATA) {
    for (const c of p.cities) {
      if (c.zip === q || c.zip.startsWith(q)) {
        out.push({ province: p.province, city: c.city, zip: c.zip });
      }
    }
  }
  return out;
}
